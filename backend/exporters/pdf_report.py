"""
pdf_report.py
=============
Premium Light-Mode Architectural Report Generator (ReportLab Platypus).

Generates a multi-page PDF with:
  Page 1: Cover — hero project metadata
  Page 2: Executive Summary (area, rooms, scores at a glance)
  Page 3: Floor Plan image(s) per floor
  Page 4: Vastu Shastra Analysis
  Page 5: NBC Compliance
  Page 6: Energy Efficiency
  Page 7: Sunlight Analysis
  Page 8: Bill of Materials & Cost Estimate

Light mode: white background, dark ink — professional print-ready.
Returns raw PDF bytes suitable for a FastAPI Response download.
"""

