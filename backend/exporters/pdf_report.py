SECTION_NBC    = colors.HexColor("#7c3aed")   # Purple for NBC


# ── INR formatter ─────────────────────────────────────────────────────────────
def _inr(amount: float) -> str:
    if amount >= 1_00_00_000:
        return f"Rs. {amount / 1_00_00_000:.2f} Cr"
    if amount >= 1_00_000:
        return f"Rs. {amount / 1_00_000:.2f} L"
    return f"Rs. {amount:,.0f}"


# ── Page canvas callback — draws the header/footer on every page ──────────────
def _draw_header_footer(canvas, doc):
    canvas.saveState()
    w, h = A4

    # Top bar — white background, thin accent bottom border, logo on left
    canvas.setFillColor(colors.white)
    canvas.rect(0, h - 1.2 * cm, w, 1.2 * cm, fill=1, stroke=0)
    canvas.setStrokeColor(BRAND_ACCENT)
    canvas.setLineWidth(2)
    canvas.line(0, h - 1.2 * cm, w, h - 1.2 * cm)

    # Logo text
    canvas.setFillColor(BRAND_ACCENT)
    canvas.setFont("Helvetica-Bold", 9)
    canvas.drawString(1.5 * cm, h - 0.82 * cm, "⬡ AI ARCHITECT")
    canvas.setFillColor(BRAND_MID)
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(w - 1.5 * cm, h - 0.82 * cm, "ARCHITECTURAL PROJECT DOSSIER")

    # Footer — thin top line
    canvas.setStrokeColor(BRAND_BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(1.5 * cm, 1.0 * cm, w - 1.5 * cm, 1.0 * cm)
    canvas.setFillColor(BRAND_MID)
    canvas.setFont("Helvetica", 7)
    canvas.drawString(1.5 * cm, 0.5 * cm, "Generated by AI Architect · For illustrative purposes only · Verify with a licensed architect before construction")
    canvas.drawRightString(w - 1.5 * cm, 0.5 * cm, f"Page {doc.page}")

    canvas.restoreState()


